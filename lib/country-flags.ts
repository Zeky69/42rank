// Conversion d'un nom de pays (tel que renvoyé par l'API 42) en drapeau emoji.
// La table couvre tous les pays ISO 3166-1 ; la normalisation (minuscules,
// sans accents ni ponctuation) absorbe les variantes d'écriture.

function normalize(s: string): string {
  let out = "";
  for (const ch of s.normalize("NFD").toLowerCase()) {
    const code = ch.codePointAt(0)!;
    // Ignore les marques combinantes (accents décomposés) U+0300–U+036F.
    if (code >= 0x0300 && code <= 0x036f) continue;
    if ((ch >= "a" && ch <= "z") || (ch >= "0" && ch <= "9")) out += ch;
  }
  return out;
}

