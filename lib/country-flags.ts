const LOOKUP: Record<string, string> = {};
for (const [name, iso] of Object.entries(RAW)) LOOKUP[normalize(name)] = iso;
for (const [name, iso] of Object.entries(ALIASES)) LOOKUP[normalize(name)] = iso;

export function countryFlag(country?: string): string {
  if (!country) return "🌐";
  const iso = LOOKUP[normalize(country)];
  if (!iso) return "🌐";
  return iso
    .toUpperCase()
    .replace(/./g, (ch) => String.fromCodePoint(127397 + ch.charCodeAt(0)));
}
